def test_no_template_interpolates_data_into_an_inline_confirm():
    """The class of bug, not just this instance. Server-generated identifiers
    such as a work order number are fine; anything a user can type is not."""
    from pathlib import Path
    templates = (Path(__file__).resolve().parent.parent / 'app' / 'templates')
    offenders = []
    for path in templates.rglob('*.html'):
        for line in path.read_text().split('\n'):
            if 'onclick=' in line and 'confirm(' in line and '{{' in line:
                # wo_number is generated by the app (WO-YYYY-NNNNN), never typed.
                if 'wo_number' not in line:
                    offenders.append(f'{path.name}: {line.strip()[:90]}')
    assert not offenders, 'user-supplied text inside an inline confirm:\n' + '\n'.join(offenders)
